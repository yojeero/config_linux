# mbr
выберите «Ручная разметка» (Manual partitioning) и создайте структуру разделов строго по спецификации CachyOS для MBR/BIOS:

Раздел под /boot (Загрузчик):
Размер: не менее 4096 МиБ (4 ГБ) — это критично, CachyOS использует «жирные» ядра, на меньшем объеме установка вылетит.

Файловая система: ext4 (или FAT32, если планируете использовать Limine).

Точка монтирования: /boot.
Флаги: отметьте флаг boot.
Корневой раздел /:
Размер: всё оставшееся место (минимум 20 ГБ).
Файловая система: ext4 (или XFS / BTRFS).
Точка монтирования: /.

Выбор загрузчика:В выпадающем списке внизу экрана «Установить загрузчик на:» выберите сам жесткий диск (например, /dev/sda), а не отдельный раздел (например, /dev/sda1).

В качестве загрузчика выберите GRUB

