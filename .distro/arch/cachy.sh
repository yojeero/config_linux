Запуск консольного установщика CachyOS CLI Installer (который основан на скриптах вроде ABIF/archinstall) — это отличный способ обойти баги графического Calamares на старых MBR/BIOS системах. Консольный инсталлятор гораздо стабильнее работает с разметкой дисков, меньше потребляет ОЗУ и не вылетает без объяснения причин.

## Как запустить CLI-установщик в Live-сессии:

   1. Откройте стандартный Терминал в Live-режиме CachyOS.
   2. Введите команду для запуска консольного меню:
   
   cachyos-cli-installer
   
   (Если команда не найдена, попробуйте sudo cachyos-cli-installer или проверьте актуальное имя скрипта в меню CachyOS Hello).

## Пошаговое прохождение MBR/BIOS установки через CLI:
Интерфейс представляет собой текстовое интерактивное меню, по которому нужно перемещаться стрелочками и клавишей Enter.
## Шаг 1: Подготовка диска (Prepare Installation)

* Set Virtual Console: Выберите вашу раскладку клавиатуры (можно оставить us).
* Partition Disk: Выберите ваш жесткий диск (например, /dev/sda).
* Важно для MBR: Выберите утилиту cfdisk. Нажмите Enter. В появившемся окне выберите тип таблицы dos (это и есть MBR).
* Создайте разделы:
1. New -> Размер 4G -> Type -> выберите Linux boot. Обязательно нажмите Bootable (появится звездочка в графе Flags).
   2. New -> Выделите всё оставшееся место под корень -> Type -> Linux root.
   3. Перейдите на кнопку Write, введите yes для сохранения, затем нажмите Quit.

## Шаг 2: Монтирование (Mount Partitions)

* Выбирайте по очереди разделы, которые только что создали:
* Большой раздел (например, sda2) примонтируйте как / (root). Текстовый установщик предложит выбрать файловую систему — для старых ПК и MBR лучше выбрать проверенную ext4.
   * Маленький раздел 4 ГБ (например, sda1) примонтируйте строго в /boot.

## Шаг 3: Настройка зеркал и обновление ключей

* Выберите Configure Installer Mirrorlist.
* Обязательно запустите Refresh Pacman Keys перед установкой. Это исключит вылеты из-за просроченных цифровых подписей пакетов.

## Шаг 4: Установка системы (Install System)

* Install Base Packages: Начнется скачивание базовой системы.
* Install Desktop: Выберите ваше окружение (KDE, XFCE и т.д.). 
* Install Bootloader:
* Критически важно: Из предложенных вариантов выберите GRUB. На MBR-разметке systemd-boot работать не будет!
   * Скрипт спросит, куда ставить загрузочный сектор. Укажите сам диск (целиком /dev/sda), а не отдельный раздел. 

## Шаг 5: Конфигурация (Configure Base)

* Задайте Имя хоста (Hostname), Часовой пояс (Timezone), Пароль Root и Создайте пользователя (Add New User).
* После завершения всех пунктов выберите Reboot для перезагрузки в готовую систему.


