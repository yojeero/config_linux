
# ----------------------------------
# Micro Keybidings
# ----------------------------------
Ctrl + q = Quit
Ctrl + o = Open
Ctrl + s = Save
Ctrl + f = Find
Ctrl + n = Find next
Ctrl + p = Find previous
Ctrl + z = Undo
Ctrl + y = Redo
Ctrl + c = Copy
Ctrl + x = Cut
Ctrl + k = Cut line
Ctrl + v = Paste
Ctrl + a = Select all
Ctrl + l = Jump line
PageUp = Cusor moves up a full page
PageDown = Cursor moves down a full page
Ctrl + w = Next split
Ctrl + t = Add a Tab
Ctrl + / = Next Tab
Ctrl + b = Shell mode
Alt + left/right = move the cursor a word in that direction
Ctrl + u = Toggle Macro (recoding keystrokes?)
Ctrl + j = Play Macro (play recorded steps)